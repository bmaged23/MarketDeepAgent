"""Generate schema diagrams from migrations, never from a customer's database.

Run: python docs/generate.py. Uses only the standard library and project SQL.
"""
import html
import sqlite3
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.database.connection import migrate

ASSETS = ROOT / 'docs/assets'


def schema():
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / 'schema.db'
        migrate(path)
        with sqlite3.connect(path) as db:
            names = [r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
                     if not r[0].startswith('product_fts_')]
            return {name: {'columns': list(db.execute(f'PRAGMA table_info("{name}")')),
                           'foreign_keys': list(db.execute(f'PRAGMA foreign_key_list("{name}")'))} for name in names}


def erd(tables):
    positions = {}; body = []; relationships = []
    for i, (name, info) in enumerate(tables.items()):
        x = 28 + (i % 3) * 390; y = 65 + (i // 3) * 600
        height = 48 + 23 * len(info['columns']); positions[name] = (x, y, height)
        body.append(f'<g><rect class="entity" x="{x}" y="{y}" width="350" height="{height}" rx="10"/><text class="title" x="{x+15}" y="{y+29}">{name}</text>')
        foreign = {r[3] for r in info['foreign_keys']}
        for j, col in enumerate(info['columns']):
            _, field, kind, required, default, primary = col
            key = ('PK ' if primary else '') + ('FK ' if field in foreign else '')
            text = html.escape(f'{key}{field}: {kind or "TEXT"}' + (' NOT NULL' if required else ''))
            body.append(f'<text x="{x+15}" y="{y+53+j*23}">{text}</text>')
        body.append('</g>')
        for fk in info['foreign_keys']:
            relationships.append((name, fk[2], fk[3], fk[4]))
    links = []
    for source, target, field, target_field in relationships:
        if target not in positions: continue
        x,y,h = positions[source]; tx,ty,th = positions[target]
        links.append(f'<path class="relation" d="M {x+350} {y+22} C {x+380} {y+22}, {tx-22} {ty+22}, {tx} {ty+22}" marker-end="url(#arrow)"><title>{source}.{field} → {target}.{target_field or "primary key"}</title></path>')
    height = 90 + ((len(tables)+2)//3)*600
    header = svg_start(1200,height) + '<text class="heading" x="28" y="35">SQLite ERD · generated from all migrations</text>'
    ASSETS.joinpath('database-erd.svg').write_text(header + ''.join(links+body) + '</svg>')
    lines = ['# Database relationships', '', 'Generated by `python docs/generate.py` from all six migrations.', '', '```mermaid','erDiagram']
    for name, info in tables.items():
        lines.append(f'    {name} {{')
        for col in info['columns']:
            kind = col[2].split('(')[0] or 'TEXT'
            lines.append(f'        {kind} {col[1]}' + (' PK' if col[5] else ''))
        lines.append('    }')
    for source,target,field,_ in relationships:
        lines.append(f'    {target} ||--o{{ {source} : "{field}"')
    lines += ['```','','FTS shadow tables and sqlite_sequence are implementation details and omitted.','product_fts.rowid logically equals product.product_id. product_index_jobs.product_id is a durable logical reference, not an FK, so deleted products can retain cleanup jobs.',
              '', '## Qdrant (derived indexes)', '', '| Collection | Point ID | Authoritative join / isolation |', '| --- | --- | --- |', '| market_products | SQL product_id | payload category_id = SQL category_id; revision, document_hash and embedding_model checked |', '| customer_memories | SQL memory_id | payload person_id, version and embedding_model; SQL owner/active/version checked again |', '', 'Both collections use 1024-dimensional BGE embeddings with cosine similarity. Qdrant is not a relational store; the links above are logical mappings, not database foreign keys.']
    (ROOT/'docs/database.md').write_text('\n'.join(lines)+'\n')


def svg_start(width,height):
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-label="MarketDeepAgent architecture or database diagram"><style>
    text{{font-family:Arial,sans-serif;fill:#e7edf7;font-size:12px}} .title{{font-size:17px;font-weight:bold}} .heading{{font-size:24px;font-weight:bold}}
    .entity{{fill:#16243a;stroke:#41577b;stroke-width:1.5}} .relation{{fill:none;stroke:#52708f;stroke-width:1.2;opacity:.7}}
    .flow{{fill:none;stroke:#477689;stroke-width:2;stroke-dasharray:6 7;animation:dash 1.8s linear infinite}}
    .node:hover .entity{{stroke:#6af5d3;stroke-width:3}} .signal{{fill:#6af5d3}}
    @keyframes dash{{to{{stroke-dashoffset:-26}}}} @media(prefers-reduced-motion:reduce){{.flow{{animation:none}} .signal{{display:none}}}}
    </style><defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="#6af5d3"/></marker></defs><rect width="100%" height="100%" fill="#091323"/>'''


def architecture():
    from system_diagrams import generate
    generate(ASSETS)


def main():
    ASSETS.mkdir(parents=True,exist_ok=True)
    tables=schema();erd(tables);architecture()
    print(f'Generated architecture and ERD for {len(tables)} SQLite tables.')


if __name__=='__main__':main()
